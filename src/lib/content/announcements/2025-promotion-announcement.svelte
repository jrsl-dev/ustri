<h2>Promotion Announcement</h2>

<p>
  As President of the United States Tamiya Ryu Iaijutsu Gennankai, it is my
  great honor to announce that Gennankai Head Instructor, James Russell
  (Gennetsu) Sensei, has received his promotion to Nanadan (7th Degree).
</p>

<figure>
  <img src={shinsa} alt="" />
  <figcaption>
    James Russell (Gennetsu) performs Omote no Maki Sanbonmae Yokemi
  </figcaption>
</figure>

<p>
  Gennetsu Sensei took his Nanadan Shinsa (Examination) in Japan on Sunday,
  November 9, while participating in the Annual Genwakai Autumn Shinsakai and
  Enbukai and was formally promoted to Nanadan the following day by 15th Soke
  Tsumaki Kazuo Genwa. His Nanadan Shinsa also included a separate “Guidance
  Examination” which required him to explain the inner workings of several kata
  in great detail. Thanks to the superb translation efforts of several members
  of the Genwakai, Gennetsu Sensei was given permission to use English for this
  portion of his Shinsa in order to alleviate the need to use Japanese
  exclusively. Our deepest appreciation goes out to all the translators,
  including Higashiyama-san of the Kyoto Branch and Suwa-san of the Isehara
  Branch, for their translation contributions. To all of the members of the
  Genwakai I would like to say “Osewa ni narimashita” for taking such good care
  of Gennetsu Sensei during his time in Japan.
</p>

